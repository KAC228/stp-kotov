// ─── Renderers ────────────────────────────────────────────────────────────────

function RichText({ text }: { text: string }) {
  const parts = text.split(/(\[[^\]]+\])/g);
  return (
    <span>
      {parts.map((part, i) =>
        /^\[.+\]$/.test(part) ? (
          <mark
            key={i}
            className="bg-transparent text-red-400 font-mono text-[13px] px-0.5 not-italic font-semibold"
          >
            {part}
          </mark>
        ) : (
          <span key={i}>{part}</span>
        )
      )}
    </span>
  );
}

function SectionBlock({ block }: { block: Block }) {
  if (block.type === "p") {
    return (
      <p className="text-zinc-400 text-[15px] leading-[1.8] mb-4">
        <RichText text={block.text} />
      </p>
    );
  }

  if (block.type === "ol") {
    return (
      <ol className="flex flex-col gap-3 mb-4 pl-0">
        {block.items.map((item, i) => (
          <li key={i} className="flex items-start gap-4 text-zinc-400 text-[15px] leading-relaxed">
            <span className="shrink-0 w-6 h-6 rounded-full bg-zinc-800 border border-zinc-700 flex items-center justify-center text-zinc-500 text-[11px] font-mono mt-0.5">
              {i + 1}
            </span>
            <RichText text={item} />
          </li>
        ))}
      </ol>
    );
  }

  if (block.type === "ul") {
    return (
      <ul className="flex flex-col gap-2.5 mb-4 pl-0">
        {block.items.map((item, i) => (
          <li key={i} className="flex items-start gap-3 text-zinc-400 text-[15px] leading-relaxed">
            <span className="shrink-0 w-1.5 h-1.5 rounded-full bg-zinc-600 mt-[9px]" />
            <RichText text={item} />
          </li>
        ))}
      </ul>
    );
  }

  if (block.type === "table") {
    return (
      <div className="overflow-x-auto mb-4 rounded-xl border border-zinc-800">
        <table className="w-full text-[14px]">
          <tbody>
            {block.rows.map(([term, def], i) => (
              <tr key={i} className="border-b border-zinc-800 last:border-none">
                <td className="py-4 px-5 align-top font-medium text-zinc-300 whitespace-nowrap w-[38%] bg-zinc-900/60">
                  <RichText text={term} />
                </td>
                <td className="py-4 px-5 align-top text-zinc-500 leading-relaxed bg-zinc-950/40">
                  <RichText text={def} />
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    );
  }

  return null;
}

