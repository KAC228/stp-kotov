export function getSystemForCategory(
  category: FlibenCategoryId
): FlibenSystem | undefined {
  if (category === "all" || category === "accessories" || category === "adapters") {
    return undefined;
  }
  return FLIBEN_SYSTEMS.find((s) => s.id === category);
}
